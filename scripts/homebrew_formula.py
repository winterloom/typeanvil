#!/usr/bin/env python3
"""Generate the Homebrew formula (typeanvil.rb) from a release's SHA256SUMS.

Usage:
    python3 scripts/homebrew_formula.py --version 2026.10.0 \
        --sums dist/SHA256SUMS --repo winterloom/typeanvil -o typeanvil.rb

Spec: docs/specifications/homebrew-tap.spec.md (CORE-137).
"""
import argparse
import re
import sys

# Formula platform block -> release target triple.
TARGETS = {
    "macos_arm": "aarch64-apple-darwin",
    "macos_intel": "x86_64-apple-darwin",
    "linux_intel": "x86_64-unknown-linux-musl",
    "linux_arm": "aarch64-unknown-linux-gnu",
}

CALVER = re.compile(r"^[0-9]{4}\.[0-9]{1,2}\.[0-9]+$")


def parse_sums(text):
    """Return {filename: sha256} from sha256sum output."""
    sums = {}
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        m = re.match(r"^([0-9a-f]{64})\s+\*?(\S+)$", line)
        if not m:
            raise ValueError(f"bad SHA256SUMS line: {line!r}")
        sums[m.group(2)] = m.group(1)
    return sums


def render(version, sums, repo):
    if not CALVER.match(version):
        raise ValueError(f"version {version!r} is not CalVer YYYY.M.PATCH")
    shas = {}
    for key, target in TARGETS.items():
        name = f"typeanvil-{version}-{target}.tar.gz"
        if name not in sums:
            raise ValueError(f"SHA256SUMS has no entry for {name}")
        shas[key] = sums[name]

    def url(key):
        t = TARGETS[key]
        return (f"https://github.com/{repo}/releases/download/v{version}/"
                f"typeanvil-{version}-{t}.tar.gz")

    def block(key):
        return f'      url "{url(key)}"\n      sha256 "{shas[key]}"\n'

    return f'''# Generated by scripts/homebrew_formula.py (CORE-137). Do not hand-edit:
# the release workflow rewrites url/sha256 on every tag.
class Typeanvil < Formula
  desc "AI-first HTML/Markdown to PDF typesetting engine"
  homepage "https://github.com/{repo}"
  version "{version}"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
{block("macos_arm")}    end
    on_intel do
{block("macos_intel")}    end
  end

  on_linux do
    on_arm do
{block("linux_arm")}    end
    on_intel do
{block("linux_intel")}    end
  end

  def install
    bin.install "typeanvil"
  end

  test do
    assert_match "typeanvil #{{version}}", shell_output("#{{bin}}/typeanvil --version")
    (testpath/"in.html").write "<!DOCTYPE html><html><body><p>Hello Typeanvil</p></body></html>"
    system bin/"typeanvil", "render", testpath/"in.html",
           "--page-width", "8.5in", "--page-height", "11in", "-o", testpath/"out.pdf"
    assert_predicate testpath/"out.pdf", :size?
  end
end
'''


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--version", required=True)
    ap.add_argument("--sums", required=True)
    ap.add_argument("--repo", default="winterloom/typeanvil")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args(argv)
    with open(a.sums) as f:
        sums = parse_sums(f.read())
    try:
        out = render(a.version, sums, a.repo)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    with open(a.output, "w") as f:
        f.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
